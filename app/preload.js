  connectClaude: email => ipcRenderer.invoke('connect-claude', email),
  authCode: c => ipcRenderer.send('auth-code', c),
  connectGemini: () => ipcRenderer.invoke('connect-gemini'),
  testGemini: k => ipcRenderer.invoke('test-gemini', k),
