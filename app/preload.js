  getConfig: () => ipcRenderer.invoke('get-config'),
  setIgnore: v => ipcRenderer.send('set-ignore', v),
  focus: () => ipcRenderer.send('focus-pet'),
  ask: (id, text) => ipcRenderer.send('ask', { id, text }),
  cancel: () => ipcRenderer.send('cancel'),
